"""Forensic report export (JSON + standalone HTML)."""
from __future__ import annotations

import json
from pathlib import Path

_DISCLAIMER = ("This report is generated by probabilistic AI forensic analysis. "
               "It is not definitive legal proof of authenticity or manipulation.")


def to_json(result: dict) -> str:
    payload = dict(result)
    payload["disclaimer"] = _DISCLAIMER
    return json.dumps(payload, indent=2, default=str)


def to_html(result: dict) -> str:
    rows = []
    for key, sig in result.get("signals", {}).items():
        if isinstance(sig, dict):
            rows.append(f"<tr><td>{key}</td><td>{sig.get('score')}</td>"
                        f"<td>{sig.get('confidence')}</td><td>{sig.get('explanation','')}</td></tr>")
    evidence = "".join(f"<li>{e['explanation']}</li>" for e in result.get("evidence", []))
    return f"""<html><head><meta charset='utf-8'><title>Forensic Report</title></head><body>
<h1>Digital Forensics Report</h1>
<p><b>File:</b> {result.get('filename')} &nbsp; <b>Type:</b> {result.get('media_type')} &nbsp;
<b>Analyzed:</b> {result.get('analyzed_at')}</p>
<h2>Authenticity Score: {result.get('authenticity_score')} / 100</h2>
<p><b>Verdict:</b> {result.get('verdict')} &nbsp; <b>Confidence:</b> {result.get('confidence')}</p>
<h3>Signals</h3>
<table border='1' cellpadding='6' cellspacing='0'>
<tr><th>Signal</th><th>Score</th><th>Confidence</th><th>Explanation</th></tr>
{''.join(rows)}</table>
<h3>Evidence</h3><ul>{evidence}</ul>
<h3>Limitations</h3><ul>{''.join(f'<li>{l}</li>' for l in result.get('limitations', []))}</ul>
<p><i>{_DISCLAIMER}</i></p>
</body></html>"""


def save_report(result: dict, out_dir: str, stem: str) -> dict:
    out = Path(out_dir)
    out.mkdir(parents=True, exist_ok=True)
    j = out / f"{stem}_report.json"
    h = out / f"{stem}_report.html"
    j.write_text(to_json(result), encoding="utf-8")
    h.write_text(to_html(result), encoding="utf-8")
    return {"json": str(j), "html": str(h)}
